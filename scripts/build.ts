// Builds the standalone release into dist/: one `cinnamon` binary per Mac architecture with Bun and all of Cinnamon's
// files inside, so installing needs neither Homebrew nor Bun.
//   bun scripts/build.ts            → dist/cinnamon-darwin-arm64.tar.gz, dist/cinnamon-darwin-x64.tar.gz, dist/SHA256SUMS
//   bun scripts/build.ts --arch=arm64   only this Mac's architecture (quicker, for trying it out)
// Steps: build Cinnamon Helper once as a universal app (arm64 + x86_64, signed), lay out the payload (core, themes,
// extensions, types, package.json and the prebuilt helper), generate an entry that embeds every payload file
// (`with { type: 'file' }`) and hands them to core/standalone/Standalone.ts, then `bun build --compile` per target.
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { helperSourceHash, Installer } from '../core/install/Installer';

const ROOT = path.join(import.meta.dir, '..');
const WORK = path.join(ROOT, 'build', 'standalone');
const DIST = path.join(ROOT, 'dist');
const PAYLOAD_DIRS = ['core', 'extensions', 'themes', 'types'];
const PAYLOAD_FILES = ['package.json'];
const TARGETS = { arm64: 'bun-darwin-arm64', x64: 'bun-darwin-x64-baseline' } as const;
type Arch = keyof typeof TARGETS;

function run(cmd: string, args: string[], opts: { cwd?: string } = {}): string {
  const r = spawnSync(cmd, args, { encoding: 'utf8', cwd: opts.cwd });
  if (r.status !== 0) throw new Error(`${cmd} ${args.join(' ')} failed:\n${r.stderr || r.stdout}`);
  return r.stdout;
}

function walk(dir: string): string[] {
  const out: string[] = [];
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (e.name === '.DS_Store' || e.name === 'node_modules') continue;
    const p = path.join(dir, e.name);
    if (e.isDirectory()) out.push(...walk(p));
    else if (e.isFile()) out.push(p);
  }
  return out;
}

/** Cinnamon Helper as a universal app, signed ad hoc with the identifier macOS's Accessibility list keys on. */
function buildHelper(payload: string): void {
  const app = path.join(payload, 'prebuilt', 'Cinnamon Helper.app');
  const exe = path.join(app, 'Contents', 'MacOS', 'cinnamon-helper');
  fs.mkdirSync(path.dirname(exe), { recursive: true });
  fs.copyFileSync(path.join(ROOT, 'core', 'helper', 'Info.plist'), path.join(app, 'Contents', 'Info.plist'));
  const slices = ['arm64', 'x86_64'].map((a) => {
    const out = path.join(WORK, `helper-${a}`);
    run('swiftc', ['-O', '-target', `${a}-apple-macos12`, '-o', out, path.join(ROOT, 'core', 'helper', 'main.swift')]);
    return out;
  });
  run('lipo', ['-create', '-output', exe, ...slices]);
  run('codesign', ['--force', '--sign', '-', '--identifier', Installer.LABEL, app]);
  fs.writeFileSync(path.join(payload, 'prebuilt', '.built-from'), `${helperSourceHash(ROOT)}\n`);
}

function layOut(payload: string): string[] {
  for (const d of PAYLOAD_DIRS) fs.cpSync(path.join(ROOT, d), path.join(payload, d), { recursive: true, filter: (src) => !/(^|\/)(\.DS_Store|node_modules)$/.test(src) });
  for (const f of PAYLOAD_FILES) fs.copyFileSync(path.join(ROOT, f), path.join(payload, f));
  buildHelper(payload);
  return walk(payload).map((f) => path.relative(payload, f)).sort();
}

function writeEntry(payload: string, files: string[], version: string): string {
  const entry = path.join(WORK, 'entry.ts');
  const lines = [
    '// Generated by scripts/build.ts: the standalone binary\'s entry, embedding every payload file.',
    `import { runStandalone } from ${JSON.stringify(path.join(ROOT, 'core', 'standalone', 'Standalone.ts'))};`,
    ...files.map((f, i) => `import f${i} from ${JSON.stringify(path.join(payload, f))} with { type: 'file' };`),
    'const files: Record<string, string> = {',
    ...files.map((f, i) => `  ${JSON.stringify(f)}: f${i},`),
    '};',
    `runStandalone(files, ${JSON.stringify(version)}, process.argv.slice(2)).then((code) => process.exit(code ?? 0), (e) => { console.error(e); process.exit(1); });`,
  ];
  fs.writeFileSync(entry, `${lines.join('\n')}\n`);
  return entry;
}

function compile(entry: string, arch: Arch): string {
  const outDir = path.join(WORK, arch);
  fs.mkdirSync(outDir, { recursive: true });
  const bin = path.join(outDir, 'cinnamon');
  run('bun', ['build', '--compile', `--target=${TARGETS[arch]}`, entry, '--outfile', bin], { cwd: ROOT });
  run('codesign', ['--force', '--sign', '-', bin]);
  return bin;
}

export async function build(arches: Arch[] = ['arm64', 'x64']): Promise<string[]> {
  const version = (JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8')) as { version: string }).version;
  fs.rmSync(WORK, { recursive: true, force: true });
  fs.rmSync(DIST, { recursive: true, force: true });
  fs.mkdirSync(DIST, { recursive: true });
  const payload = path.join(WORK, 'payload');
  const files = layOut(payload);
  const entry = writeEntry(payload, files, version);
  const sums: string[] = [];
  const outputs: string[] = [];
  for (const arch of arches) {
    const bin = compile(entry, arch);
    const tarball = path.join(DIST, `cinnamon-darwin-${arch}.tar.gz`);
    run('tar', ['-czf', tarball, '-C', path.dirname(bin), 'cinnamon']);
    sums.push(`${createHash('sha256').update(fs.readFileSync(tarball)).digest('hex')}  ${path.basename(tarball)}`);
    outputs.push(tarball);
    console.log(`built ${path.relative(ROOT, tarball)} (${(fs.statSync(tarball).size / 1e6).toFixed(1)} MB, Cinnamon ${version}, ${files.length} files)`);
  }
  fs.writeFileSync(path.join(DIST, 'SHA256SUMS'), `${sums.join('\n')}\n`);
  return outputs;
}

if (import.meta.main) {
  const only = process.argv.find((a) => a.startsWith('--arch='))?.slice(7) as Arch | undefined;
  if (only && !(only in TARGETS)) { console.error(`--arch must be one of ${Object.keys(TARGETS).join(', ')}`); process.exit(64); }
  await build(only ? [only] : undefined);
}
